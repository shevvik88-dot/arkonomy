  const { beginOperation } = await freshModule();
  const a = beginOperation('user-1', 'SPY', 30);
  const b = beginOperation('user-2', 'SPY', 30);
  assert.notEqual(a.id, b.id);
  assert.equal(b.isRetry, false);
